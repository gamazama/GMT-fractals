/**
 * gen-dcc-templates - turn the two DCC import scripts into a TS module.
 *
 * The .py files are the source of truth: they are the owner's tested scripts and they stay
 * runnable Python, editable in a Python editor, diffable as Python. They cannot be pulled
 * in with Vite's `?raw` though - palette/core/exportFormats.ts is imported by the node-run
 * guards (test:palette and its 28 harnesses), and node cannot resolve a `?raw` specifier,
 * so one of them anywhere in that import graph takes the whole suite down. That is not a
 * hypothetical: it is how this was written first, and test:palette went red.
 *
 * So they are transcribed into a generated module instead, mechanically, never by hand.
 * `npm run check:dcc` fails if the generated file has drifted from the .py.
 *
 * Run: npm run gen:dcc
 */
import { readFileSync, writeFileSync } from 'fs';

const NL = String.fromCharCode(10);
const CR = String.fromCharCode(13);
const SRC = new URL('../palette/core/dcc/', import.meta.url);
const FILES = [
  ['c4dImport.py', 'C4D_IMPORT_PY'],
  ['blenderImport.py', 'BLENDER_IMPORT_PY'],
];

/** The generated module's exact contents, so the check can compare without writing. */
export const render = () => {
  const body = FILES.map(([file, name]) => {
    // Normalise CRLF before embedding: a stray CR would make the generated file differ
    // from the .py on one machine and not another.
    const src = readFileSync(new URL(file, SRC), 'utf8').split(CR).join('');
    return '/** Verbatim from ./' + file + '. */' + NL +
      'export const ' + name + ' = ' + JSON.stringify(src) + ';' + NL;
  }).join(NL);
  return '/* AUTO-GENERATED by debug/gen-dcc-templates.mjs - do not edit.' + NL +
    ' * Edit the .py files beside this one and re-run `npm run gen:dcc`.' + NL +
    ' * `npm run check:dcc` fails if this file and the .py have drifted apart. */' + NL + NL +
    body;
};

export const OUT = new URL('templates.generated.ts', SRC);

if (process.argv[1] && process.argv[1].endsWith('gen-dcc-templates.mjs')) {
  writeFileSync(OUT, render(), 'utf8');
  console.log('wrote palette/core/dcc/templates.generated.ts');
}
