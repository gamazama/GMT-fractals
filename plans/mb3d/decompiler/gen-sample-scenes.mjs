// Bundle the faithfully-renderable .m3p sample scenes into a TS module (base64),
// so the importer can offer them as click-to-load samples without the files.
import fs from 'node:fs';
import path from 'node:path';
import { registry } from '../../GMT/workspace-gmt/stable/engine-gmt/engine/FractalRegistry.ts';
import { AmazingBox } from '../../GMT/workspace-gmt/stable/engine-gmt/formulas/AmazingBox.ts';
import { parseMB3DBinary } from '../../GMT/workspace-gmt/stable/engine-gmt/utils/mb3d/parseMB3D.ts';
import { emitFusedHybrid } from '../../GMT/workspace-gmt/stable/engine-gmt/utils/mb3d/emitFusedHybrid.ts';

registry.register(AmazingBox);
const dir = 'h:/tmp/mb3d-src/M3Parameter';
// Imports-cleanly but renders WRONG → exclude from the bundled list (user-curated).
//   spineJulia: interior −Z Integer-Power bulb renders solid white; needs interior/deep-zoom GMT lacks.
//   Aexion 10bulbs: _PolyFolding→_updateC→Aexion1 weave — NO slot writes dr and none are dIFS, so the
//     r/dr estimator marches against dr=1 → DE≈r → "dust" (the Oxnot true-no-derivative class; needs the
//     deferred est-7 auto-route for provably-no-deriv weaves + numDEeps calibration). Decode (#4 Cw) is correct.
//   Dainbramage - Hydra: _JuliaSets (no-deriv lattice) woven with 3 dIFS slots (IcosahedronIFS/ABoxPlatinumB/
//     koch_oct) → estimator-mix + re-lattice on weave cycles → noisy surface. _JuliaSets decode (#3) is correct
//     (JuliaSetSample, its simple _JuliaSets→IntegerPower weave, renders faithfully); the noise is this scene's
//     dIFS/non-dIFS DE interaction, a DE-fidelity residual, not the input-coord decode.
const SKIP = new Set(['spineJulia', 'Aexion 10bulbs', 'Dainbramage - Hydra']);
const files = fs.readdirSync(dir).filter((f) => f.toLowerCase().endsWith('.m3p')).sort();
const scenes = [];
for (const f of files) {
  const name = f.replace(/\.m3p$/i, '');
  if (SKIP.has(name)) continue;
  const bytes = new Uint8Array(fs.readFileSync(path.join(dir, f)));
  try {
    const scene = parseMB3DBinary(bytes, name);
    const { def, ledger } = emitFusedHybrid(scene);
    if (!def) continue; // faithful only (skip best-effort / unsupported)
    scenes.push({ name: f.replace(/\.m3p$/i, ''), formulas: ledger.slotFlags.map((s) => s.name), b64: Buffer.from(bytes).toString('base64') });
  } catch {}
}

let ts = `/* AUTO-GENERATED by plans/mb3d/decompiler/gen-sample-scenes.mjs — do not edit.\n`;
ts += ` * Faithfully-renderable Mandelbulb3D .m3p sample scenes (from thargor6/mb3d\n`;
ts += ` * M3Parameter/), base64-encoded so the importer can offer them as click-to-load\n`;
ts += ` * samples. A scene qualifies only if every slot decompiles + weaves (mode 0). */\n\n`;
ts += `export interface SampleScene { name: string; formulas: string[]; b64: string; }\n\n`;
ts += `export const MB3D_SAMPLE_SCENES: SampleScene[] = [\n`;
for (const s of scenes) ts += `  ${JSON.stringify(s)},\n`;
ts += `];\n\n`;
ts += `/** Decode a sample scene's base64 to the raw .m3p bytes. */\n`;
ts += `export function decodeSampleScene(b64: string): Uint8Array {\n`;
ts += `  const bin = atob(b64);\n`;
ts += `  const out = new Uint8Array(bin.length);\n`;
ts += `  for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);\n`;
ts += `  return out;\n`;
ts += `}\n`;

const out = 'h:/GMT/workspace-gmt/stable/engine-gmt/utils/mb3d/sampleScenes.ts';
fs.writeFileSync(out, ts, 'utf8');
console.log(`wrote ${out}: ${scenes.length} faithful sample scenes`);
console.log(scenes.map((s) => s.name).join('\n'));
